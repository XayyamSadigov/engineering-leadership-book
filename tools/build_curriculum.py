#!/usr/bin/env python3
"""Generate the pages that are derived from curriculum.yaml and research/bibliography.yaml.

    python tools/build_curriculum.py           # write the generated pages
    python tools/build_curriculum.py --check   # exit 1 if any generated page is stale

Generated (do not edit by hand):
    docs/curriculum.md
    docs/references/bibliography.md
    docs/exercises/index.md
"""
from __future__ import annotations

import sys
from pathlib import Path

from booklib import DOCS, LIVE, Report, iter_chapters, load_bibliography, load_curriculum, rel

HEADER = "<!-- GENERATED by tools/build_curriculum.py. Edit {src}, then rerun the tool. -->\n\n"
STATUS_LABEL = {
    "published": "Published",
    "review": "On the site, awaiting human review",
    "draft": "In draft",
    "planned": "Planned",
}
CLASS_LABEL = {
    "scholarly": "Scholarly research",
    "industry-research": "Industry research",
    "standard": "Standard or framework",
    "official-documentation": "Official documentation",
    "practitioner": "Practitioner literature",
}
ACCESS_LABEL = {
    "full-text": "full text read",
    "abstract-only": "abstract or landing page only",
    "official-summary": "official summary read",
    "metadata-only": "bibliographic metadata only; the work itself was not read for this entry",
}


def curriculum_page() -> str:
    cur = load_curriculum()
    chapters = list(iter_chapters())
    published = [c for c in chapters if c.status == "published"]
    review = [c for c in chapters if c.status == "review"]
    out = [HEADER.format(src="curriculum.yaml"), "# Curriculum\n"]
    out.append(
        f"The book is designed as {len(chapters)} chapters in {len(cur['parts'])} parts. "
        f"**{len(published)} of {len(chapters)} chapters are published, and {len(review)} more "
        f"{'is' if len(review) == 1 else 'are'} on the site awaiting human review.** "
        "A chapter is published only when it passes the automated validation and the human "
        "review checklist. A chapter awaiting review has passed the "
        "automated validation and carries a banner saying so. Planned chapters are designed "
        "(objectives and sources below) but not yet written, and do not appear in the site "
        "navigation.\n"
    )
    out.append("| Part | Chapters | On the site |\n|---|---|---|")
    for part in cur["parts"]:
        chs = part.get("chapters") or []
        pub = sum(1 for c in chs if c["status"] in LIVE)
        span = f"{chs[0]['n']}–{chs[-1]['n']}" if len(chs) > 1 else (str(chs[0]["n"]) if chs else "templates")
        out.append(f"| {part['roman']}. {part['title']} | {span} | {pub} of {len(chs)} |")
    out.append("")
    for part in cur["parts"]:
        out.append(f"## Part {part['roman']} — {part['title']}\n")
        out.append(part["summary"] + "\n")
        for ch in part.get("chapters") or []:
            c = next(x for x in chapters if x.n == ch["n"])
            title = f"Chapter {c.n} — {c.title}"
            if c.status in LIVE:
                title = f"[{title}]({c.rel_path})"
            out.append(f"### {title}\n")
            out.append(f"*Status: {STATUS_LABEL[c.status]}*"
                       + (f" · *Project: {c.project.upper()}*" if c.project else "") + "\n")
            out.append("After this chapter you can:\n")
            out.extend(f"- {o}" for o in c.objectives)
            out.append("")
            if c.sources:
                refs = ", ".join(f"[{s}](references/bibliography.md#{s})" for s in c.sources)
                out.append(f"Primary sources: {refs}\n")
        if part["slug"] == "14-playbooks":
            out.append("| Template | Status |\n|---|---|")
            for t in cur["templates"]:
                name = f"[{t['title']}](templates/{t['file']})" if t["status"] in LIVE else t["title"]
                out.append(f"| {name} | {STATUS_LABEL[t['status']]} |")
            out.append("")
    out.append("## Practical projects\n")
    out.append("| Project | Status |\n|---|---|")
    for p in cur["projects"]:
        out.append(f"| {p['id'].upper()}: {p['title']} | {STATUS_LABEL[p['status']]} |")
    out.append("")
    return "\n".join(out)


def format_entry(e: dict) -> str:
    authors = e.get("authors") or []
    if len(authors) > 4:
        who = f"{authors[0]} et al."
    elif len(authors) > 1:
        who = ", ".join(authors[:-1]) + f", and {authors[-1]}"
    else:
        who = authors[0] if authors else "Unknown"
    if e.get("role") == "editors":
        who += " (eds.)"
    title = e["title"] + (f": {e['subtitle']}" if e.get("subtitle") else "")
    title = f"*{title}*" if e["type"] in ("book", "report", "standard") else f"“{title}”"
    where = e.get("publisher") or e.get("venue") or ""
    year = e.get("year") or "n.d."
    lines = [f"### {e['id']} {{#{e['id']}}}\n"]
    cite = f"{who} ({year}). {title}." + (f" {where}." if where else "")
    if e.get("edition_note"):
        cite += f" {e['edition_note']}"
    lines.append(cite + "\n")
    facts = []
    if e.get("doi"):
        facts.append(f"DOI: [{e['doi']}](https://doi.org/{e['doi']})")
    if e.get("isbn13"):
        facts.append(f"ISBN-13: {e['isbn13']}")
    if e.get("url"):
        facts.append(f"<{e['url']}>")
    if e.get("free_online"):
        facts.append(f"Free online: <{e['free_online']}>")
    if facts:
        lines.append("- " + " · ".join(facts))
    lines.append(f"- Evidence class: {CLASS_LABEL[e['evidence_class']]}. "
                 f"Access for this bibliography: {ACCESS_LABEL[e['access_level']]}.")
    verified = e.get("verified_fields") or []
    if verified:
        lines.append(f"- Verified against a fetched page ({e.get('verified_on', 'date not recorded')}): "
                     + ", ".join(verified) + ".")
    else:
        lines.append("- **Not verified.** Do not cite in a published chapter.")
    if e.get("notes"):
        lines.append(f"- Note: {e['notes']}")
    for claim in e.get("claims") or []:
        lines.append(f"- Supports ({claim['basis']}): {claim['text']}")
    if e.get("caveats"):
        lines.append(f"- Caveats: {e['caveats']}")
    return "\n".join(lines) + "\n"


def bibliography_page() -> str:
    entries = load_bibliography()
    out = [HEADER.format(src="research/bibliography.yaml"), "# Bibliography\n"]
    out.append(
        "Every source the book cites, with what was verified and how much of the source was "
        "actually read when the entry was created. An entry marked *bibliographic metadata only* "
        "means the citation details were checked against a publisher or catalog page; it does "
        "not mean the work was read in full for this project. Chapters cite by linking to the "
        "anchors on this page.\n"
    )
    out.append(f"{len(entries)} entries. Grouped by evidence class, then alphabetically by id.\n")
    for cls in ("scholarly", "industry-research", "standard", "official-documentation", "practitioner"):
        group = sorted((e for e in entries if e["evidence_class"] == cls), key=lambda e: e["id"])
        if not group:
            continue
        out.append(f"## {CLASS_LABEL[cls]}\n")
        out.extend(format_entry(e) for e in group)
    return "\n".join(out)


def exercises_page() -> str:
    out = [HEADER.format(src="curriculum.yaml"), "# Exercises and solutions\n"]
    out.append(
        "Exercises live at the end of each chapter, in three levels: **Foundational** (F), "
        "**Applied Leadership** (A), and **Executive Decision-Making** (X). Worked solutions are "
        "kept in separate files so that you can attempt the work first. Most exercises have more "
        "than one defensible answer; the solutions show one worked answer and the criteria a "
        "good answer must meet.\n"
    )
    out.append("| Chapter | Exercises | Solutions |\n|---|---|---|")
    for c in iter_chapters("live"):
        out.append(f"| {c.n}. {c.title} | [Exercises](../{c.rel_path}#exercises) | "
                   f"[Solutions](../{c.solutions_rel_path}) |")
    out.append("")
    return "\n".join(out)


TARGETS = {
    DOCS / "curriculum.md": curriculum_page,
    DOCS / "references" / "bibliography.md": bibliography_page,
    DOCS / "exercises" / "index.md": exercises_page,
}


def run(check: bool = False) -> int:
    rep = Report("generated-pages")
    for path, fn in TARGETS.items():
        content = fn().rstrip() + "\n"
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if check:
            if current != content:
                rep.error(f"{rel(path)} is stale; run python tools/build_curriculum.py")
        else:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            if current != content:
                path.write_text(content, encoding="utf-8")
                rep.note(f"wrote {rel(path)}")
    return rep.finish()


if __name__ == "__main__":
    sys.exit(run(check="--check" in sys.argv))
