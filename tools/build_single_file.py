#!/usr/bin/env python3
"""Assemble the single-file edition: dist/ENGINEERING_LEADERSHIP_HANDBOOK.md

    python tools/build_single_file.py           # write the file
    python tools/build_single_file.py --check   # exit 1 if the file on disk is stale

The order follows the mkdocs nav, so the single file and the site never disagree about what is in
the book. Every included page gets an anchor; links between included pages are rewritten to those
anchors, headings are demoted one level so that each page title becomes an H2 under its nav group.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any

from booklib import DIST, DOCS, FENCE_RE, LINK_RE, MKDOCS, Report, load_curriculum, load_yaml, rel

OUT = DIST / "ENGINEERING_LEADERSHIP_HANDBOOK.md"


def nav_groups() -> list[tuple[str, list[str]]]:
    """Flatten the nav into (group title, [files]) preserving order."""
    groups: list[tuple[str, list[str]]] = []

    def collect(node: Any) -> list[str]:
        files: list[str] = []
        if isinstance(node, str):
            files.append(node)
        elif isinstance(node, list):
            for item in node:
                files.extend(collect(item))
        elif isinstance(node, dict):
            for value in node.values():
                files.extend(collect(value))
        return files

    for item in load_yaml(MKDOCS)["nav"]:
        if isinstance(item, dict):
            for title, value in item.items():
                groups.append((title, collect(value)))
        else:
            groups.append(("", collect(item)))
    return groups


def page_anchor(rel_path: str) -> str:
    return "page-" + re.sub(r"[^a-z0-9]+", "-", rel_path.lower().removesuffix(".md")).strip("-")


def transform(rel_path: str, included: set[str]) -> str:
    src = DOCS / rel_path
    text = src.read_text(encoding="utf-8")
    text = re.sub(r"^<!-- GENERATED.*?-->\n+", "", text, flags=re.S)
    out: list[str] = []
    fence: str | None = None
    for line in text.splitlines():
        stripped = line.strip()
        m = FENCE_RE.match(stripped)
        if fence is None and m:
            fence = m.group(1)[0] * 3
            out.append(line)
            continue
        if fence is not None:
            if stripped.startswith(fence) and stripped.strip(fence[0]) == "":
                fence = None
            out.append(line)
            continue
        if re.match(r"^#{1,5}\s", line):
            line = "#" + line

        def fix(match: re.Match[str]) -> str:
            label, target = match.group(1), match.group(2)
            if re.match(r"^[a-z][a-z0-9+.-]*:", target):
                return match.group(0)
            file_part, _, anchor = target.partition("#")
            if not file_part:
                return match.group(0)
            dest = (src.parent / file_part).resolve()
            try:
                dest_rel = str(dest.relative_to(DOCS))
            except ValueError:
                return label
            if dest_rel in included:
                return f"[{label}](#{anchor or page_anchor(dest_rel)})"
            return label

        out.append(LINK_RE.sub(fix, line))
    return f'<a id="{page_anchor(rel_path)}"></a>\n\n' + "\n".join(out).strip() + "\n"


def build() -> str:
    cur = load_curriculum()
    groups = nav_groups()
    included = {f for _, files in groups for f in files}
    parts = [
        f"# {cur['book']['title']}\n",
        f"**{cur['book']['subtitle']}**\n",
        "Single-file edition, generated by `tools/build_single_file.py` from the same sources as "
        "the website. Text is licensed CC BY 4.0; see LICENSE-CONTENT.md in the repository. "
        "Northstar Technologies and every person, number, and dataset attached to it are "
        "fictional.\n",
        "## Contents\n",
    ]
    for title, files in groups:
        if title:
            parts.append(f"- **{title}**")
        for f in files:
            first = (DOCS / f).read_text(encoding="utf-8")
            first = re.sub(r"^<!--.*?-->\n+", "", first, flags=re.S)
            m = re.search(r"^#\s+(.+)$", first, re.M)
            name = m.group(1).strip() if m else f
            indent = "  " if title else ""
            parts.append(f"{indent}- [{name}](#{page_anchor(f)})")
    parts.append("")
    for title, files in groups:
        if title:
            parts.append(f"\n---\n\n# {title}\n")
        for f in files:
            parts.append(transform(f, included))
    return "\n".join(parts).rstrip() + "\n"


def run(check: bool = False) -> int:
    rep = Report("single-file")
    content = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if check:
        if current != content:
            rep.error(f"{rel(OUT)} is stale; run python tools/build_single_file.py")
    else:
        Path(DIST).mkdir(exist_ok=True)
        OUT.write_text(content, encoding="utf-8")
        rep.note(f"wrote {rel(OUT)} ({len(content.split()):,} words)")
    return rep.finish()


if __name__ == "__main__":
    sys.exit(run(check="--check" in sys.argv))
